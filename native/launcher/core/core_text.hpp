// ---- session.ini ----------------------------------------------------------------
struct SessionIni {
    std::string role;                 // host | guest | echo | solo (debug tools only)
    std::string transport = "steam";  // steam | udp
    std::string peer_steamid;         // guest: the host's SteamID64 (from the code)
    std::string secret;               // host: new; guest: from the code; echo / solo: ""
    std::string udp_peer;             // udp: the partner's IPv4
    int udp_port_local = 0;           // udp: 1..65535
    int udp_port_peer = 0;
    int send_hz = 30;                 // 1..120
    int interp_delay_ms = 100;        // 0..1000
    double echo_delay_s = 2.0;        // 0..10 (the mod's range)
    double echo_offset_m = 1.5;       // 0..20
    bool partner_activate = true;     // wake the spawned partner clone
    bool verbose = false;
    bool debug_menu = true;           // the in-game debug menu
    int debug_menu_key = 9;           // its key, F1..F12 (written as "F9")
    bool dev_tools = false;           // dev_tools=1: the debug menu's Dev tools page (written only when set)
    // The mod renames session.ini to session.last.ini as soon as it has read it,
    // so a later plain Steam launch runs unmodded. Every launch writes it.
    bool one_shot = true;
    std::string name;                 // optional display name
    // Test saves and the local two-instance test (docs/sandbox-and-local-test.md; read by the
    // mod in DllMain, native/mod/sandbox.hpp). Written only when sandbox_saves is set.
    std::string sandbox_saves;        // a folder name under stranded_together\sandbox ("" = the real saves)
    bool sandbox_foreign_saves = false;   // skip ds.exe's save-owner check (another account's save)
    bool appdir_settings = false;     // the game folder's settings.cfg -> the sandbox's settings.cfg
    bool second_instance = false;     // the second game on this PC (its single-instance mutex is renamed)
    // The host-held save session (M1, docs/coop-session.md): the host plays on its own saves and the guest's game only
    // ever runs on the private coop-guest folder, loading the copy of the host's save the link brings. Written as
    // host_save=1 for a host or a guest. A guest with host_save is refused unless sandbox_saves=coop-guest and
    // sandbox_foreign_saves=1 come with it (the guest never runs a co-op session on its own saves; the mod refuses too).
    bool host_save = false;
    std::string local_input;          // host | host_pad | guest ("" = a normal game)
    int frame_cap = 0;                // 0 or 15..240 frames per second
    std::string local_window;         // left | right: the game window takes that half of the monitor
    // mouse_lock=1 (the Local test, Debug option "Lock the mouse to the focused game window"): the cursor stays inside the
    // game window that is in front (F10 switches game, Alt+Tab leaves). Written only when set; parsed strictly (0 / 1).
    bool mouse_lock = false;
    // world_sync (shared structures, ziplines, ladders and ropes, docs/world-sync.md): structures either player builds appear
    // in both worlds. The Debug option "Share structures, ladders, ropes and ziplines" (default on) for Host, Join and the
    // Local test; with host_save the line is always written (world_sync=0 when off: the mod's default is on with
    // host_save=1); parsed strictly (0 / 1).
    bool world_sync = false;
    // The real partner body (docs/real-partner-body.md). my_character: the character THIS player
    // appears as on the other player's screen, an offered native/mod/body_table.cpp key; the mod
    // sends it as STJ1 body_id. The host is always Sam: the writer puts my_character=sam for a host
    // whatever this says (the mod does the same). "" = not written (the mod uses sam).
    std::string my_character;
    std::string partner_body;         // real | holo: how the partner is drawn ("" = not written, the mod's default)
    // Self view: on this player's own screen the local Sam is shown as my_character too. Written
    // (self_character=1) only for a non-host whose my_character is set and is not sam; the mod
    // treats a missing key as off.
    bool self_character = false;
    // Self voice (docs/audio-research.md section 9, Phase 1): auto | sam | mute (self_voice_setting.hpp). auto =
    // the mod mutes Sam's voice on this player's game when their character is not Sam. Written whenever set;
    // "" = not written (the mod then keeps Sam's voice). The writer refuses other values.
    std::string self_voice = "auto";
    // Partner voice (docs/audio-research.md section 15, Phase 2): voice_sync=1 is written when set; the mod's
    // default (no key) is off.
    bool voice_sync = false;
    // Partner sounds (docs/audio-research.md section 16, Phase 3): sound_sync=1 is written when set; the mod's default (no
    // key) is off.
    bool sound_sync = false;
    // Partner sound volume (Phase 4, 0..100): partner_volume=N is written only with sound_sync and N below 100 (the mod's
    // default is 100). The writer refuses values outside 0..100.
    int partner_volume = 100;

    // Name tags (the partner's name above their head; ours sent to them). The mod's default is
    // on: only name_tags=0 is written.
    bool name_tags = true;
    // Player collision (the partner's real body blocks you). The mod's default is on: only
    // partner_collision=0 is written.
    bool partner_collision = true;
    // Vehicle hits (docs/real-partner-body.md section 25): the partner's vehicles damage and knock down THIS player's Sam
    // (each game decides for its own Sam). The mod's default is on: only partner_vehicle_damage=0 is written.
    bool partner_vehicle_damage = true;
};
