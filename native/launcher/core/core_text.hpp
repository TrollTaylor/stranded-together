// Stranded Together launcher core: the pure text of a co-op session. No I/O.
//  - session.ini, the contract with the in-game mod (winhttp.dll): written by
//    the launcher before the game starts, deleted after it exits;
//  - link-status.json, written by the mod about once a second, read back here
//    into the In game page's view;
//  - secrets, SteamIDs and log redaction.
// Adapted from Diamond Dogs Together's core_text (lab.ini / coop.ini became one
// session.ini; the MGSV status sentences, missions and launch evidence are gone).
#pragma once
#include <cstdint>
#include <string>
#include <utility>
#include <vector>

#include "core_json.hpp"

namespace st::core {

// ---- Constants ---------------------------------------------------------------
inline constexpr char kAlphabet[] = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";   // Crockford base32
// The first line of every session.ini this program writes.
inline constexpr char kHeader[] = "# Generated by Stranded Together";
inline constexpr std::uint32_t kSteamAppId = 1850570;
inline constexpr char kSteamUrl[] = "steam://rungameid/1850570";
inline constexpr std::uint64_t kSteamIdBase = 76561197960265728ull;
// A link-status.json older than this (or written by a process that is gone) is stale.
inline constexpr std::int64_t kStatusStaleMs = 15000;
inline constexpr int kDefaultUdpPort = 27555;

// ---- Secrets, Steam IDs -------------------------------------------------------
bool IsCanonicalSecret(const std::string& secret);   // 20 characters of kAlphabet
std::string NewSecret();                              // 100 bits: alphabet[random & 31] x 20
bool IsIndividualSteamId64(const std::string& text);  // 17 digits, no leading zero, individual account
std::string SteamId64FromAccount(std::uint32_t account);   // "" for 0
bool IsCanonicalIPv4(const std::string& text);        // a.b.c.d, no leading zeros
// A display name the ini can carry: printable ASCII, no '#', ';', '=' or quotes, 1..32 chars.
bool IsValidPlayerName(const std::string& name);

// ---- session.ini ----------------------------------------------------------------
struct SessionIni {
    std::string role;                 // host | guest | echo | solo (debug tools only)
    std::string transport = "steam";  // steam | udp
    std::string peer_steamid;         // guest: the host's SteamID64 (from the code)
    std::string secret;               // host: new; guest: from the code; echo / solo: ""
    std::string udp_peer;             // udp: the partner's IPv4
    int udp_port_local = 0;           // udp: 1..65535
    int udp_port_peer = 0;
    int send_hz = 30;                 // 1..120
    int interp_delay_ms = 100;        // 0..1000
    double echo_delay_s = 2.0;        // 0..10 (the mod's range)
    double echo_offset_m = 1.5;       // 0..20
    bool partner_activate = true;     // wake the spawned partner clone
    bool verbose = false;
    bool debug_menu = true;           // the in-game debug menu
    int debug_menu_key = 9;           // its key, F1..F12 (written as "F9")
    // The mod renames session.ini to session.last.ini as soon as it has read it,
    // so a later plain Steam launch runs unmodded. Every launch writes it.
    bool one_shot = true;
    std::string name;                 // optional display name
    // Test saves and the local two-instance test (docs/sandbox-and-local-test.md; read by the
    // mod in DllMain, native/mod/sandbox.hpp). Written only when sandbox_saves is set.
    std::string sandbox_saves;        // a folder name under stranded_together\sandbox ("" = the real saves)
    bool sandbox_foreign_saves = false;   // skip ds.exe's save-owner check (another account's save)
    bool appdir_settings = false;     // the game folder's settings.cfg -> the sandbox's settings.cfg
    bool second_instance = false;     // the second game on this PC (its single-instance mutex is renamed)
    std::string local_input;          // host | host_pad | guest ("" = a normal game)
    int frame_cap = 0;                // 0 or 15..240 frames per second
    std::string local_window;         // left | right: the game window takes that half of the monitor
};
inline constexpr double kMaxEchoDelayS = 10.0;
inline constexpr double kMaxEchoOffsetM = 20.0;
// "F1".."F12" -> 1..12 (case-insensitive); 0 for anything else.
int ParseFunctionKey(const std::string& text);
std::string FunctionKeyName(int key);   // 9 -> "F9"; "" outside 1..12
// The file text (LF line ends, kHeader first). False + a reason for invalid fields.
bool MakeSessionIniText(const SessionIni& ini, std::string& text, std::string& error);
// The reverse (tests, the self-test and join_code() after a window was reopened):
// key=value lines; unknown keys are ignored. False + a reason when a field is malformed.
bool ParseSessionIniText(const std::string& text, SessionIni& out, std::string& error);
bool IsGeneratedIniText(const std::string& text);   // starts with kHeader
// key=value lines, '#'/';' comments, trimmed; later keys win.
std::vector<std::pair<std::string, std::string>> ParseIni(const std::string& text);

// ---- link-status.json -----------------------------------------------------------
// link-status.json -> object, or null when it is not v1, has no state or
// (expected_pid != 0) another process wrote it.
json::Value ParseStatusText(const std::string& text, std::uint32_t expected_pid);

// What the In game page shows. Built from the status (or its absence) by LinkViewOf.
struct StatusView {
    std::string state;        // the mod's state, "" when there is no usable status
    bool fresh = false;       // written within kStatusStaleMs by a running game
    bool connected = false;
    int rtt_ms = 0;           // <= 0 unknown
    std::string transport, route, peer, remote, reason;
    std::string headline;     // one short line
    std::string detail;       // one or two plain sentences
    enum class Tone { neutral, good, warn, bad } tone = Tone::neutral;
};
// role: host | guest | echo. `status` is ParseStatusText's result (null = none yet);
// `fresh` = its time_utc is within kStatusStaleMs and its pid runs.
StatusView StatusViewOf(const json::Value& status, bool fresh, const std::string& role);
// The mod's "peer" for the screen: "steam:<SteamID64>" becomes "Steam player ...1234"
// (no full SteamID on screen); anything else (a LAN "ip:port", a name) is kept.
std::string PeerDisplay(const std::string& peer);
// The freshness rule on its own: time_utc parses and now - time <= kStatusStaleMs.
bool StatusTimeFresh(const json::Value& status, std::int64_t now_ms);

// ---- Redaction -------------------------------------------------------------------
std::string MaskAddress(const std::string& address);   // a public IPv4's last two parts -> x.x
std::string RedactSensitive(const std::string& text);   // SteamIDs, userdata accounts, user names
std::string RedactNetwork(const std::string& text);     // join codes, invite strings, secrets, public peer addresses
std::string Redact(const std::string& text);            // both
// For launcher.log: Redact plus every drive path replaced by "<path>".
std::string RedactForLog(const std::string& text);

}  // namespace st::core
